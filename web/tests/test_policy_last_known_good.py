from __future__ import annotations

import importlib
from pathlib import Path

import pytest


@pytest.fixture
def lkg_dir(tmp_path, monkeypatch) -> Path:
    path = tmp_path / "durable" / "policy-last-known-good"
    monkeypatch.setenv("PROXY_POLICY_LKG_DIR", str(path))
    return path


def test_remember_and_restore_policy_include(tmp_path, lkg_dir) -> None:
    from services import policy_materializer  # type: ignore

    include = tmp_path / "conf.d" / "30-webfilter.conf"
    include.parent.mkdir()
    assert (
        policy_materializer.restore_last_known_good_policy_file(str(include)) is False
    )

    policy_materializer.remember_last_known_good_policy_files(
        [(str(include), "acl webfilter_block_ads external x ads\n")],
    )
    include.write_text(
        "# Autogenerated: web filtering disabled (apply failed)\n", encoding="utf-8"
    )

    assert policy_materializer.restore_last_known_good_policy_file(str(include))
    assert (
        include.read_text(encoding="utf-8")
        == "acl webfilter_block_ads external x ads\n"
    )


@pytest.mark.parametrize(
    ("tool", "store_module", "store_class", "safe_marker"),
    [
        (
            "sslfilter_apply",
            "services.sslfilter_store",
            "SslFilterStore",
            "sslfilter apply failed",
        ),
        (
            "webfilter_apply",
            "services.webfilter_core",
            "ProxyWebFilterStore",
            "web filtering disabled",
        ),
    ],
)
def test_apply_helper_restores_last_applied_include_when_control_plane_fails(
    tmp_path,
    lkg_dir,
    monkeypatch,
    tool,
    store_module,
    store_class,
    safe_marker,
) -> None:
    module = importlib.reload(importlib.import_module(f"tools.{tool}"))
    out = tmp_path / "conf.d" / f"{tool}.conf"
    out.parent.mkdir()
    applied = "# Autogenerated: policy\nssl_bump splice all\n"
    mode = {"fail": False}

    class Store:
        def __init__(self, *, squid_include_path: str) -> None:
            self.path = squid_include_path
            self.last_webcat_snapshot_status = (True, "")

        def apply_squid_include(self) -> None:
            if mode["fail"]:
                msg = "Database is unavailable."
                raise RuntimeError(msg)
            Path(self.path).write_text(applied, encoding="utf-8")

    monkeypatch.setattr(importlib.import_module(store_module), store_class, Store)

    # A successful apply is mirrored to the durable volume.
    assert module.main(["--out", str(out)]) == 0

    # A failed apply keeps serving it instead of an empty include.
    out.unlink()
    mode["fail"] = True
    assert module.main(["--out", str(out)]) == 3
    assert out.read_text(encoding="utf-8") == applied

    # Boot without the control plane skips the database entirely.
    out.unlink()
    assert module.main(["--out", str(out), "--last-known-good-only"]) == 0
    assert out.read_text(encoding="utf-8") == applied

    # Without any mirror the safe include is still published.
    for item in lkg_dir.iterdir():
        item.unlink()
    assert module.main(["--out", str(out), "--last-known-good-only"]) == 5
    assert safe_marker in out.read_text(encoding="utf-8")


_STARTUP_ICAP = (
    "icap_service adblock_req reqmod_precache icap://127.0.0.1:14000/adblockreq bypass=on\n"
    "icap_service av_resp respmod_precache icap://127.0.0.1:14002/avrespmod bypass=on\n"
    "# Adblock request routing disabled by ADBLOCK_ENABLED=0 startup setting.\n"
    "adaptation_access adblock_req_set deny all\n"
)
_APPLIED_ICAP = (
    "icap_service adblock_req_e2fa reqmod_precache icap://127.0.0.1:14000/adblockreq bypass=on\n"
    "icap_service av_resp respmod_precache icap://127.0.0.1:14002/avrespmod bypass=on\n"
    "adaptation_access adblock_req_set allow icap_adblockable\n"
)


def test_boot_restores_last_applied_icap_policy_for_same_services(
    tmp_path, lkg_dir
) -> None:
    from services import policy_materializer  # type: ignore

    include = tmp_path / "20-icap.conf"
    virus = tmp_path / "virus_scan.conf"
    include.write_text(_STARTUP_ICAP, encoding="utf-8")
    virus.write_text("# image default\n", encoding="utf-8")
    assert not policy_materializer.restore_last_known_good_icap_runtime(
        str(include), str(virus)
    )

    policy_materializer.remember_last_known_good_policy_files(
        [(str(include), _APPLIED_ICAP), (str(virus), "virus_scan.MaxObjectSize 64M\n")],
    )

    assert policy_materializer.restore_last_known_good_icap_runtime(
        str(include), str(virus)
    )
    assert include.read_text(encoding="utf-8") == _APPLIED_ICAP
    assert virus.read_text(encoding="utf-8") == "virus_scan.MaxObjectSize 64M\n"


def test_boot_keeps_startup_icap_include_when_services_changed(
    tmp_path, lkg_dir
) -> None:
    from services import policy_materializer  # type: ignore

    include = tmp_path / "20-icap.conf"
    virus = tmp_path / "virus_scan.conf"
    policy_materializer.remember_last_known_good_policy_files(
        [(str(include), _APPLIED_ICAP)],
    )
    # Worker count/ports changed since the mirror was taken: its ICAP service
    # URIs no longer match this boot, so the safe startup include stays.
    rebased = _STARTUP_ICAP.replace("14002", "14004")
    include.write_text(rebased, encoding="utf-8")

    assert not policy_materializer.restore_last_known_good_icap_runtime(
        str(include), str(virus)
    )
    assert include.read_text(encoding="utf-8") == rebased
