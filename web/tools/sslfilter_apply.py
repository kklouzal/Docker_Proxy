#!/usr/bin/env python3
from __future__ import annotations

import argparse
import pathlib
import sys
from typing import TYPE_CHECKING

try:
    from tools.apply_common import emit_helper_failure, write_safe_include
except ModuleNotFoundError:  # pragma: no cover - direct script execution path
    from apply_common import emit_helper_failure, write_safe_include

if TYPE_CHECKING:
    from collections.abc import Sequence

HELPER_NAME = "sslfilter_apply"
SAFE_INCLUDE_TEXT = "# Autogenerated: sslfilter apply failed\n"


def _emit_failure(event: str, exc: Exception) -> None:
    emit_helper_failure(HELPER_NAME, event, exc)


def _write_safe_include(path: str) -> None:
    write_safe_include(path, SAFE_INCLUDE_TEXT)


def _publish_safe_include(path: str) -> None:
    try:
        _write_safe_include(path)
    except Exception as exc:
        _emit_failure("safe_include_publish_failed", exc)


def _restore_last_known_good(path: str) -> bool:
    """Serve the last policy this proxy applied when the control plane is unavailable."""
    try:
        from services.policy_materializer import (  # type: ignore
            restore_last_known_good_policy_file,
        )

        return restore_last_known_good_policy_file(path)
    except Exception as exc:
        _emit_failure("last_known_good_restore_failed", exc)
        return False


def _remember_last_known_good(path: str) -> None:
    try:
        from services.policy_materializer import (  # type: ignore
            remember_last_known_good_policy_files,
        )

        with pathlib.Path(path).open(encoding="utf-8") as handle:
            remember_last_known_good_policy_files(((path, handle.read()),))
    except Exception as exc:
        _emit_failure("last_known_good_save_failed", exc)


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Generate /etc/squid/conf.d/10-sslfilter.conf from UI settings",
    )
    ap.add_argument("--out", default="/etc/squid/conf.d/10-sslfilter.conf")
    ap.add_argument(
        "--last-known-good-only",
        action="store_true",
        help="Skip the control-plane database and restore the last applied include.",
    )
    args = ap.parse_args(list(argv) if argv is not None else None)

    sys.path.insert(0, "/app")
    if args.last_known_good_only:
        if _restore_last_known_good(args.out):
            return 0
        _publish_safe_include(args.out)
        return 5
    try:
        from services.sslfilter_store import SslFilterStore  # type: ignore
    except Exception as exc:
        _emit_failure("import_failed", exc)
        _publish_safe_include(args.out)
        return 2

    try:
        store = SslFilterStore(squid_include_path=args.out)
        store.apply_squid_include()
    except Exception as exc:
        _emit_failure("apply_failed", exc)
        if not _restore_last_known_good(args.out):
            _publish_safe_include(args.out)
        return 3
    _remember_last_known_good(args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
