#!/usr/bin/env python3
from __future__ import annotations

import argparse
import sys
from typing import TYPE_CHECKING

try:
    from tools.apply_common import (
        emit_helper_failure,
        publish_safe_include,
        remember_last_known_good,
        restore_last_known_good,
    )
except ModuleNotFoundError:  # pragma: no cover - direct script execution path
    from apply_common import (
        emit_helper_failure,
        publish_safe_include,
        remember_last_known_good,
        restore_last_known_good,
    )

if TYPE_CHECKING:
    from collections.abc import Sequence

HELPER_NAME = "sslfilter_apply"
SAFE_INCLUDE_TEXT = "# Autogenerated: sslfilter apply failed\n"


def _publish_safe_include(path: str) -> None:
    publish_safe_include(HELPER_NAME, path, SAFE_INCLUDE_TEXT)


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Generate /etc/squid/conf.d/10-sslfilter.conf from UI settings",
    )
    ap.add_argument("--out", default="/etc/squid/conf.d/10-sslfilter.conf")
    ap.add_argument(
        "--last-known-good-only",
        action="store_true",
        help="Skip the control-plane database and restore the last applied include.",
    )
    args = ap.parse_args(list(argv) if argv is not None else None)

    sys.path.insert(0, "/app")
    if args.last_known_good_only:
        if restore_last_known_good(HELPER_NAME, args.out):
            return 0
        _publish_safe_include(args.out)
        return 5
    try:
        from services.sslfilter_store import SslFilterStore  # type: ignore
    except Exception as exc:
        emit_helper_failure(HELPER_NAME, "import_failed", exc)
        _publish_safe_include(args.out)
        return 2

    try:
        store = SslFilterStore(squid_include_path=args.out)
        store.apply_squid_include()
    except Exception as exc:
        emit_helper_failure(HELPER_NAME, "apply_failed", exc)
        if not restore_last_known_good(HELPER_NAME, args.out):
            _publish_safe_include(args.out)
        return 3
    remember_last_known_good(HELPER_NAME, args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
