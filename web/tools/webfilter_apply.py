#!/usr/bin/env python3
from __future__ import annotations

import argparse
import sys
from typing import TYPE_CHECKING

try:
    from tools.apply_common import (
        emit_helper_failure,
        publish_safe_include,
        remember_last_known_good,
        restore_last_known_good,
    )
except ModuleNotFoundError:  # pragma: no cover - direct script execution path
    from apply_common import (
        emit_helper_failure,
        publish_safe_include,
        remember_last_known_good,
        restore_last_known_good,
    )

if TYPE_CHECKING:
    from collections.abc import Sequence

HELPER_NAME = "webfilter_apply"


def _publish_safe_include(path: str, reason: str) -> None:
    publish_safe_include(
        HELPER_NAME,
        path,
        f"# Autogenerated: web filtering disabled ({reason})\n",
    )


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Generate /etc/squid/conf.d/30-webfilter.conf from UI settings",
    )
    ap.add_argument("--out", default="/etc/squid/conf.d/30-webfilter.conf")
    ap.add_argument(
        "--last-known-good-only",
        action="store_true",
        help="Skip the control-plane database and restore the last applied include.",
    )
    args = ap.parse_args(list(argv) if argv is not None else None)

    # Import from the app package (works in container where /app is present).
    sys.path.insert(0, "/app")
    if args.last_known_good_only:
        if restore_last_known_good(HELPER_NAME, args.out):
            return 0
        _publish_safe_include(args.out, "control plane unavailable")
        return 5
    try:
        from services.webfilter_core import ProxyWebFilterStore
    except Exception as exc:
        emit_helper_failure(HELPER_NAME, "import_failed", exc)
        _publish_safe_include(args.out, "import failed")
        return 2

    store = ProxyWebFilterStore(squid_include_path=args.out)
    try:
        store.apply_squid_include()
    except Exception as exc:
        emit_helper_failure(HELPER_NAME, "apply_failed", exc)
        if not restore_last_known_good(HELPER_NAME, args.out):
            # Ensure include exists so Squid include is safe.
            _publish_safe_include(args.out, "apply failed")
        return 3
    remember_last_known_good(HELPER_NAME, args.out)
    snapshot_ok, snapshot_detail = getattr(
        store,
        "last_webcat_snapshot_status",
        (True, ""),
    )
    if not snapshot_ok:
        emit_helper_failure(
            HELPER_NAME,
            "snapshot_publish_failed",
            ValueError(snapshot_detail or "Web category snapshot publish failed."),
        )
        return 4
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
